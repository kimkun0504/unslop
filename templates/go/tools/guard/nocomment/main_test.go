package main

import (
	"bytes"
	"os"
	"path/filepath"
	"strings"
	"testing"
)

func write(t *testing.T, name, content string) string {
	t.Helper()
	path := filepath.Join(t.TempDir(), name)
	err := os.WriteFile(path, []byte(content), 0o600)
	if err != nil {
		t.Fatal(err)
	}
	return path
}

func TestCheckReportsCommentsAndAllowsDirectives(t *testing.T) {
	t.Parallel()
	clean := write(t, "clean.go", "//go:build linux\n\npackage x\n\n//go:generate echo\nvar s = \"// not a comment\"\n")
	dirty := write(t, "dirty.go", "package x\n\n// explains\nvar y = 1 /* note */\n")
	skipped := write(t, "notes.txt", "// ignored\n")
	var out bytes.Buffer
	count, err := check(strings.NewReader(strings.Join([]string{clean, dirty, skipped}, "\n")), &out)
	if err != nil || count != 2 || strings.Count(out.String(), "comments are forbidden") != 2 {
		t.Fatalf("count=%d err=%v out=%q", count, err, out.String())
	}
}

func TestCheckAllowsGeneratedFiles(t *testing.T) {
	t.Parallel()
	generated := write(t, "gen.go", "// Code generated by tool. DO NOT EDIT.\n\npackage x\n")
	count, err := check(strings.NewReader(generated), &bytes.Buffer{})
	if err != nil || count != 0 {
		t.Fatalf("count=%d err=%v", count, err)
	}
}

func TestCheckFailsOnUnparsableFiles(t *testing.T) {
	t.Parallel()
	broken := write(t, "broken.go", "package\n")
	_, err := check(strings.NewReader(broken), &bytes.Buffer{})
	if err == nil {
		t.Fatal("expected a parse error")
	}
}
