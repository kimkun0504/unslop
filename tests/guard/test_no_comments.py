import importlib.util
import sys
from pathlib import Path

import pytest

GUARD = Path(__file__).resolve().parents[2] / "common" / "tools" / "guard" / "no_comments.py"
spec = importlib.util.spec_from_file_location("no_comments", GUARD)
assert spec is not None
assert spec.loader is not None
no_comments = importlib.util.module_from_spec(spec)
sys.modules["no_comments"] = no_comments
spec.loader.exec_module(no_comments)

FLAGGED = {
    "a.py": 'x = "# not a comment"\n# real\ny = 1  # trailing\n',
    "a.ts": 'const u = "http://x // no";\n// real\n/* block */\nconst t = `/* no */`;\n',
    "a.tsx": "export const C = () => <div>{/* jsx */}</div>;\n",
    "a.js": "const r = /\\/\\/ no/;\n// real\n",
    "a.go": 'package x\n\n// real\nvar s = "// no"\n',
    "a.rs": 'fn main() { let s = "// no"; }\n/// doc\n//! inner\n',
    "a.java": 'class A { String s = "/* no */"; /** doc */ void f() {} }\n',
    "a.kt": 'val s = "// no"\n// real\n',
    "a.cs": 'class A { string s = "// no"; } // real\n',
    "a.swift": 'let s = "// no"\n/* real */\n',
    "a.rb": "s = '# no'\n# real\n",
    "a.php": "<?php\n$s = '// no';\n# real\n",
    "a.c": 'char *s = "/* no */";\n// real\n',
    "a.cpp": 'auto s = "// no";\n/* real */\n',
    "a.scala": 'val s = "// no"\n// real\n',
    "a.sh": "#!/usr/bin/env bash\necho '# no'\n# real\n",
    "a.sql": "select '-- no';\n-- real\n",
    "main.tf": 'locals { s = "# no" }\n# real\n',
    "a.lua": 'local s = "-- no"\n-- real\n',
    "a.ex": 'x = "# no"\n# real\n',
    "a.dart": 'var s = "// no";\n// real\n',
    "a.css": ".a { content: '/* no */'; }\n/* real */\n",
    "Dockerfile": "# syntax=docker/dockerfile:1\nFROM scratch\n# real\n",
}
EXPECTED_COUNTS = {"a.py": 2, "a.ts": 2, "a.rs": 2, "a.java": 1}

CLEAN = {
    "b.py": "#!/usr/bin/env python3\n# -*- coding: utf-8 -*-\nx = 1\n",
    "b.go": "//go:build linux\n\npackage x\n\n//go:generate echo\nvar y = 1\n",
    "b.d.ts": '/// <reference types="vite/client" />\nexport type A = string;\n',
    "Package.swift": "// swift-tools-version:6.0\nlet x = 1\n",
    "gen.go": "// Code generated by protoc. DO NOT EDIT.\n\npackage x\n\n// kept\n",
    "c.yaml": "# config comments are allowed\na: 1\n",
    ".terraform.lock.hcl": '# This file is maintained automatically by "terraform init".\nprovider "x" {}\n',
    "c.json": "{}\n",
    "README.md": "<!-- docs are not source -->\n",
}


@pytest.mark.parametrize(("name", "content"), FLAGGED.items())
def test_flags_real_comments(tmp_path: Path, name: str, content: str) -> None:
    path = tmp_path / name
    _ = path.write_text(content)
    found = no_comments.violations(path)
    assert len(found) == EXPECTED_COUNTS.get(name, 1), [v.render() for v in found]


@pytest.mark.parametrize(("name", "content"), CLEAN.items())
def test_allows_directives_strings_and_non_source(tmp_path: Path, name: str, content: str) -> None:
    path = tmp_path / name
    _ = path.write_text(content)
    assert no_comments.violations(path) == []


def test_main_reports_and_exits_nonzero(tmp_path: Path, capsys: pytest.CaptureFixture[str]) -> None:
    dirty = tmp_path / "x.py"
    _ = dirty.write_text("# real\n")
    clean = tmp_path / "y.py"
    _ = clean.write_text("y = 1\n")
    assert no_comments.main([str(dirty), str(clean)]) == 1
    assert capsys.readouterr().out == f"{dirty}:1:1: comments are forbidden (ADR-0001)\n"
    assert no_comments.main([str(clean)]) == 0
