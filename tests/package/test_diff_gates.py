from pathlib import Path

from conftest import commit, write
from unslop import comments, diffcheck, gitops


def base_with(repo: Path, files: dict[str, str]) -> str:
    for name, content in files.items():
        write(repo / name, content)
    commit(repo, "base")
    return gitops.git("rev-parse", "HEAD").strip()


def test_added_suppression_is_caught(repo: Path) -> None:
    since = base_with(repo, {"src/app.py": "x = 1\n"})
    write(repo / "src/app.py", "x = 1\ny = int('2')  # noqa: E501\n")
    found = diffcheck.suppressions(since)
    assert [problem.detail for problem in found] == ["src/app.py: y = int('2')  # noqa: E501"]


def test_suppression_in_new_untracked_file_is_caught(repo: Path) -> None:
    since = base_with(repo, {"README.md": "hi\n"})
    write(repo / "web/app.test.ts", "it.skip('later', () => {})\n")
    assert len(diffcheck.suppressions(since)) == 1


def test_existing_suppressions_and_non_code_files_are_ignored(repo: Path) -> None:
    since = base_with(repo, {"src/app.py": "y = 2  # noqa\n"})
    write(repo / "notes.md", "eslint-disable is mentioned here\n")
    write(repo / "src/app.py", "y = 2  # noqa\nz = 3\n")
    assert diffcheck.suppressions(since) == []


def test_appending_tests_is_allowed(repo: Path) -> None:
    since = base_with(repo, {"tests/test_money.py": "def test_a():\n    assert 1\n"})
    write(repo / "tests/test_money.py", "import math\ndef test_a():\n    assert 1\ndef test_b():\n    assert math.pi\n")
    assert diffcheck.tampered_tests(since) == []


def test_editing_an_existing_test_is_caught(repo: Path) -> None:
    since = base_with(repo, {"tests/test_money.py": "def test_a():\n    assert 1\n"})
    write(repo / "tests/test_money.py", "def test_a():\n    assert True\n")
    assert [problem.kind for problem in diffcheck.tampered_tests(since)] == ["test modified"]


def test_inserting_above_existing_tests_is_caught(repo: Path) -> None:
    since = base_with(repo, {"spec/money_spec.rb": "it works\n"})
    write(repo / "spec/money_spec.rb", "it first\nit works\n")
    assert len(diffcheck.tampered_tests(since)) == 1


def test_deleting_a_test_is_caught(repo: Path) -> None:
    since = base_with(repo, {"src/a.test.ts": "it('a', () => {})\n", "src/a.ts": "export {}\n"})
    (repo / "src/a.test.ts").unlink()
    assert [problem.kind for problem in diffcheck.tampered_tests(since)] == ["test deleted"]


def test_comments_only_on_added_lines(repo: Path) -> None:
    since = base_with(repo, {"src/app.py": "# legacy comment\nx = 1\n"})
    write(repo / "src/app.py", "# legacy comment\nx = 1\ny = 2  # new comment\n")
    found = comments.check(since)
    assert [(violation.path, violation.line) for violation in found] == [("src/app.py", 3)]


def test_comments_everywhere_without_a_base(repo: Path) -> None:
    write(repo / "src/app.py", "# a comment\nx = 1\n")
    write(repo / ".unslop/out/tool.py", "# ignored\n")
    assert len(comments.check(None)) == 1


def test_directives_and_generated_files_are_not_comments(repo: Path) -> None:
    since = base_with(repo, {"README.md": "x\n"})
    write(repo / "main.go", "//go:build linux\npackage main\n")
    write(repo / "gen.py", "# Code generated by tool. DO NOT EDIT.\n# body\nx = 1\n")
    assert comments.check(since) == []
